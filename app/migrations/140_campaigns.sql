CREATE TABLE IF NOT EXISTS editorial_campaigns (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_post_id BIGINT UNSIGNED NOT NULL UNIQUE,
  objective VARCHAR(40) NOT NULL,
  success_measure VARCHAR(500) NOT NULL DEFAULT '',
  notes TEXT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NOT NULL,
  updated_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_campaign_source FOREIGN KEY(source_post_id) REFERENCES posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
